#!/usr/bin/env python3
"""
Capacity per edge and tier, stated with the resource that limited it.

A measured capacity is only an edge property when the edge is what saturated. The first capacity
run showed every bare edge stalling near 7,000 req/s with its own cores half idle while the origin
(one core, serving all nine requests of an iteration) was full — so a bare-vs-WADM capacity ratio
compared the origin's limit with the edge's. This report therefore prints the binding resource
next to every capacity, compares tiers only when they share it, and gives the edge-CPU-bound
capacity (edge cores ÷ CPU per request) alongside, which is continuous and independent of any
other component's limit.

Reads benchmarks/results/capacity_<edge>.json (capacity-v2, written by run_capacity_benchmark.py).

Writes:
    results/capacity_summary.md
    results/plots/capacity.png

Usage:
    python3 benchmarks/report_capacity.py [results_dir]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from edge_specs import EDGE_KEYS, EDGES, TIERS
from plot_common import COLORS, INK, INK_MUTED, _style_frame

TIER_STYLE = {"bare": (None, 1.0), "silent": ("..", 1.0), "wadm": ("///", 1.0)}
TIER_TEXT = {"bare": "bare", "silent": "WADM (silent)", "wadm": "WADM (instrumented)"}


def load(results_dir: Path) -> dict[str, dict[str, Any]]:
    out = {}
    for edge in EDGE_KEYS:
        path = results_dir / f"capacity_{edge}.json"
        if path.exists():
            doc = json.loads(path.read_text())
            if doc.get("metadata", {}).get("schema") == "capacity-v2":
                out[edge] = doc
            else:
                print(f"  ! {path.name} predates per-resource utilisation (capacity-v1); skipped")
    return out


def write_table(docs: dict[str, Any], results_dir: Path) -> Path:
    lines = [
        "# Capacity per edge and tier",
        "",
        "Generated by `benchmarks/report_capacity.py`. *Max sustained* is the highest offered rate "
        "a majority of replicates sustained (≥95% placed, ≤1% dropped, ≤0.5% failed, worst GET "
        "p95 under the SLO), as served requests/s. *Binding* is the component using the largest "
        "share of its pinned cores at the first failing rate, with that share; *below 85%* means it "
        "was busiest without being pinned at its limit — a single-worker origin queues well before "
        "100% — and the host-wide busy share (kernel networking is charged to no container) is "
        "the next suspect. "
        "*Edge-CPU-bound* is edge cores ÷ edge CPU per request at the highest sustained rate — the "
        "throughput the edge's own cores would allow, whatever else saturates first.",
        "",
        "| Edge | Tier | Max sustained (req/s) | Binding at first failure | Edge / origin / k6 / host busy "
        "| Edge CPU per request (µs) | Edge-CPU-bound (req/s) |",
        "|---|---|---|---|---|---|---|",
    ]
    for edge, doc in docs.items():
        for tier in [t for t in TIERS if t in doc["capacity"]]:
            c = doc["capacity"][tier]
            ff = c.get("first_failure") or {}
            frac = ff.get("fraction_of_cpuset") or {}
            host = next(
                (s["utilisation"]["host"].get("busy_fraction") for s in doc["steps"]
                 if s["tier"] == tier and s["offered_rate"] == ff.get("offered_rate")
                 and s["utilisation"].get("host", {}).get("available")), None,
            )
            usage = " / ".join(
                f"{frac[k]:.0%}" if k in frac else "—" for k in ("edge", "origin", "loadgen")
            ) + (f" / {host:.0%}" if host is not None else " / —")
            binding = ff.get("binding_resource")
            if binding:
                share = frac.get(binding)
                binding += f" ({share:.0%}" if share is not None else " ("
                binding += ", saturated)" if ff.get("binding_saturated") else ", below 85%)"
            lines.append(
                f"| {EDGES[edge].label} | {TIER_TEXT[tier]} | "
                f"{round(c['max_sustained_rps']) if c.get('max_sustained_rps') else '—'} | "
                f"{binding or '—'} | {usage} | "
                f"{round(c['edge_cpu_us_per_request']) if c.get('edge_cpu_us_per_request') else '—'} | "
                f"{round(c['edge_bound_rps_at_measured_cost']) if c.get('edge_bound_rps_at_measured_cost') else '—'} |"
            )
    lines += ["", "## Tier comparisons", "",
              "| Edge | Comparison | Throughput retained | Same binding resource? "
              "| Edge-CPU-bound capacity retained |", "|---|---|---|---|---|"]
    for edge, doc in docs.items():
        for key, comp in doc["capacity"].items():
            if not key.endswith("_vs_bare"):
                continue
            tier = key.removesuffix("_vs_bare")
            retained = comp.get("throughput_retained")
            edge_retained = comp.get("edge_capacity_retained_at_measured_cost")
            same = comp.get("same_binding_resource")
            lines.append(
                f"| {EDGES[edge].label} | {TIER_TEXT[tier]} vs bare | "
                f"{f'{retained:.0%}' if retained is not None else '—'} | "
                f"{'yes' if same else '**no** — not comparable'} | "
                f"{f'{edge_retained:.0%}' if edge_retained is not None else '—'} |"
            )
    path = results_dir / "capacity_summary.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def plot(docs: dict[str, Any], out_dir: Path) -> Path:
    edges = list(docs)
    tiers = [t for t in TIERS if any(t in d["capacity"] for d in docs.values())]
    fig, ax = plt.subplots(figsize=(10.5, 5.6))
    width = 0.8 / len(tiers)
    top = 0.0
    for i, edge in enumerate(edges):
        color = COLORS[EDGES[edge].label]
        for j, tier in enumerate(tiers):
            c = docs[edge]["capacity"].get(tier)
            if not c:
                continue
            x = i + (j - (len(tiers) - 1) / 2) * width
            measured = c.get("max_sustained_rps") or 0
            bound = c.get("edge_bound_rps_at_measured_cost")
            hatch, _ = TIER_STYLE[tier]
            ax.bar(x, measured, width * 0.92, color=color if tier == "bare" else "white",
                   edgecolor=color, linewidth=2, hatch=hatch, zorder=2)
            if bound:
                ax.plot([x - width * 0.4, x + width * 0.4], [bound, bound], color=INK,
                        linewidth=2, zorder=3)
                top = max(top, bound)
            binding = (c.get("first_failure") or {}).get("binding_resource") or "—"
            ax.text(x, measured + 80, binding.split(" ")[0], ha="center", va="bottom",
                    fontsize=7.5, color=INK_MUTED, rotation=90)
            top = max(top, measured)
    ax.set_xticks(range(len(edges)))
    ax.set_xticklabels([EDGES[e].label for e in edges])
    ax.set_ylabel("requests per second", fontsize=9, color=INK_MUTED)
    ax.set_ylim(0, top * 1.25)
    _style_frame(ax)
    handles = [plt.Rectangle((0, 0), 1, 1, facecolor="white" if t != "bare" else INK_MUTED,
                             edgecolor=INK_MUTED, hatch=TIER_STYLE[t][0], label=TIER_TEXT[t])
               for t in tiers]
    handles.append(plt.Line2D([], [], color=INK, linewidth=2,
                              label="edge-CPU-bound capacity at the measured cost"))
    ax.legend(handles=handles, frameon=False, fontsize=8.5, loc="upper right")
    ax.set_title("Maximum sustained throughput, and what limited it", fontsize=12, color=INK,
                 loc="left")
    fig.text(
        0.01, 0.01,
        "Bars = highest rate a majority of replicates sustained; the label above each bar is the "
        "component that saturated first at the next rate. Compare tiers' bars only where\nthat "
        "label matches. Black ticks = 2 edge cores ÷ edge CPU per request: what the edge alone "
        "would sustain at that cost, independent of the origin and the host.",
        fontsize=7.5, color=INK_MUTED, style="italic", va="bottom", linespacing=1.5,
    )
    fig.tight_layout(rect=[0, 0.08, 1, 1])
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "capacity.png"
    fig.savefig(path, dpi=150, facecolor="white")
    plt.close(fig)
    return path


def main() -> int:
    results_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else (
        Path(__file__).resolve().parent / "results"
    )
    docs = load(results_dir)
    if not docs:
        print("No capacity-v2 results. Run run_capacity_benchmark.py first.")
        return 1
    for path in (write_table(docs, results_dir), plot(docs, results_dir / "plots")):
        print(f"  wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
